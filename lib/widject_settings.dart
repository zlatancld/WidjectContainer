/// Configuration settings for the WidjectContainer package.
///
/// Use this class to configure package-wide behavior, such as enabling
/// debug logging.
class WidjectSettings {
  /// Whether to enable debug logging for WidjectContainer.
  ///
  /// In release/production builds, logs are disabled regardless of this setting.
  /// This setting only applies to debug builds.
  ///
  /// Defaults to `false`.
  static bool enableDebugLogs = false;
}

